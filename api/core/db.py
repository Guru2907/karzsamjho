"""ALL database access (task A3; Postgres on Neon since D58). Tables: checks, cases, events, chats
(docs/ARCHITECTURE.md). There is deliberately no "list every case": a case is found by its code (D59). No other file opens the database.

Two backends, same SQL, same functions:
- DATABASE_URL set (in .env / Render): Postgres, e.g. Neon. It lives outside the server, so data
  survives a Render restart or redeploy. Connections come from a small pool: opening a new one to
  Neon costs about half a second, and one request makes several calls.
- DATABASE_URL empty: SQLite, the file config.settings.db_path (DB_PATH, default ./karzsamjho.db).
  Tests and offline work use this.
The SQL is written once, in the dialect both understand (ON CONFLICT upserts, ? placeholders that
are turned into %s for Postgres). Only the schema differs (the auto-numbered event column).
Hashes are worked out by the caller (F2); this file only stores and reads them.
"""
import json
import secrets
import sqlite3
import threading
from contextlib import closing, contextmanager
from datetime import datetime, timedelta, timezone
from pathlib import Path

from api.core import config

IST = timezone(timedelta(hours=5, minutes=30))
GENESIS_HASH = "0" * 64              # prev_hash of a case's first event

_TABLES = """
CREATE TABLE IF NOT EXISTS checks (
    id           TEXT PRIMARY KEY,
    created_at   TEXT NOT NULL,
    source       TEXT,
    image_sha256 TEXT,
    verdict      TEXT,
    extra        {real},
    seconds      {real},
    engines      TEXT,
    result_json  TEXT NOT NULL,
    lang         TEXT
);
CREATE TABLE IF NOT EXISTS cases (
    id             TEXT PRIMARY KEY,
    borrower_name  TEXT NOT NULL,
    lender_name    TEXT NOT NULL,
    check_id       TEXT,
    route          TEXT,
    opened_at      TEXT NOT NULL,
    code           TEXT,
    borrower_phone TEXT,
    source         TEXT,
    telegram_chat  TEXT,
    closed_at      TEXT,
    close_reason   TEXT,
    close_note     TEXT
);
CREATE TABLE IF NOT EXISTS chats (
    chat_key TEXT PRIMARY KEY,
    lang     TEXT
);
CREATE TABLE IF NOT EXISTS events (
    seq        {serial},
    id         TEXT UNIQUE NOT NULL,
    case_id    TEXT NOT NULL REFERENCES cases(id),
    at         TEXT NOT NULL,
    channel    TEXT,
    contacted  TEXT,
    text       TEXT,
    rules      TEXT NOT NULL,
    hash       TEXT NOT NULL,
    prev_hash  TEXT NOT NULL,
    threat_type TEXT
);
CREATE TABLE IF NOT EXISTS photos (
    id        TEXT PRIMARY KEY,
    event_id  TEXT NOT NULL,
    case_id   TEXT NOT NULL REFERENCES cases(id),
    position  INTEGER NOT NULL,
    sha256    TEXT NOT NULL,
    data      {blob} NOT NULL
);
"""
# Columns added after the first release: added to an older database on start-up (D58, D59).
_LATER_COLUMNS = {"checks": ("lang",),
                  "cases": ("code", "borrower_phone", "source", "telegram_chat", "closed_at", "close_reason",
                            "close_note"),
                  "events": ("threat_type",)}
_INDEXES = """
CREATE INDEX IF NOT EXISTS events_by_case ON events(case_id, seq);
CREATE INDEX IF NOT EXISTS checks_by_image ON checks(image_sha256);
CREATE UNIQUE INDEX IF NOT EXISTS cases_by_code ON cases(code);
CREATE INDEX IF NOT EXISTS cases_by_chat ON cases(telegram_chat);
CREATE INDEX IF NOT EXISTS photos_by_case ON photos(case_id, event_id, position)
"""
_SQLITE_SCHEMA = _TABLES.format(real="REAL", serial="INTEGER PRIMARY KEY AUTOINCREMENT", blob="BLOB")
_PG_SCHEMA = _TABLES.format(real="DOUBLE PRECISION", serial="BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                            blob="BYTEA")

_ready: set[str] = set()             # databases (path or URL) whose tables already exist
_pools: dict = {}                    # Postgres URL -> connection pool
_pools_lock = threading.Lock()


def now_ist() -> str:
    return datetime.now(IST).isoformat(timespec="seconds")


def _url() -> str:
    return config.settings.database_url


def uses_postgres() -> bool:
    return bool(_url())


class _Pg:
    """A Postgres connection that takes the same calls as sqlite3: execute(sql with ?, params)."""

    def __init__(self, conn):
        self._conn = conn

    def execute(self, sql: str, params: tuple = ()):
        return self._conn.execute(sql.replace("%", "%%").replace("?", "%s"), params)

    def commit(self) -> None:
        self._conn.commit()


def _pool(url: str):
    with _pools_lock:
        if url not in _pools:
            from psycopg.rows import dict_row
            from psycopg_pool import ConnectionPool
            # prepare_threshold=None: Neon's pooled endpoint (PgBouncer) cannot keep prepared statements.
            # check: a connection Neon closed while it slept is replaced instead of failing a request.
            _pools[url] = ConnectionPool(url, min_size=1, max_size=5, timeout=20, open=True,
                                         check=ConnectionPool.check_connection,
                                         kwargs={"row_factory": dict_row, "prepare_threshold": None,
                                                 "connect_timeout": 15})
        return _pools[url]


def close_pools() -> None:
    """Close every Postgres pool (server shutdown, tests)."""
    with _pools_lock:
        for pool in _pools.values():
            pool.close()
        _pools.clear()


@contextmanager
def _db():
    """One short piece of work on the database. Postgres: a pooled connection, committed at the end
    (rolled back on an error). SQLite: a fresh connection to the file, so threads never share one."""
    url = _url()
    if url:
        if url not in _ready:
            init_db()
        with _pool(url).connection() as conn:
            yield _Pg(conn)
        return
    path = config.settings.db_path
    if path not in _ready:
        init_db()
    with closing(sqlite3.connect(path, timeout=10)) as conn:
        conn.row_factory = sqlite3.Row
        yield conn


def init_db() -> None:
    """Create the tables if they are missing, and add columns added later. Safe to call any number of times."""
    url = _url()
    if url:
        with _pool(url).connection() as conn:
            for statement in _PG_SCHEMA.split(";"):
                if statement.strip():
                    conn.execute(statement)
            for table, columns in _LATER_COLUMNS.items():
                for column in columns:
                    conn.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column} TEXT")
            for statement in _INDEXES.split(";"):
                if statement.strip():
                    conn.execute(statement)
        _ready.add(url)
        return
    path = config.settings.db_path
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with closing(sqlite3.connect(path, timeout=10)) as conn:
        conn.executescript(_SQLITE_SCHEMA)
        for table, columns in _LATER_COLUMNS.items():
            have = {r[1] for r in conn.execute(f"PRAGMA table_info({table})")}
            for column in columns:
                if column not in have:
                    conn.execute(f"ALTER TABLE {table} ADD COLUMN {column} TEXT")
        conn.executescript(_INDEXES)
        conn.commit()
    _ready.add(path)


def describe() -> str:
    """Where the data lives, for the start-up log. Never includes the password or the full URL."""
    url = _url()
    if not url:
        return f"SQLite file {config.settings.db_path}"
    from urllib.parse import urlparse
    return f"Postgres at {urlparse(url).hostname}"


# ---------------------------------------------------------------- checks
_CHECK_COLUMNS = ("id", "created_at", "source", "image_sha256", "verdict", "extra", "seconds", "engines",
                  "result_json", "lang")


def save_check(result: dict, image_sha256: str | None, source: str, replace: bool = True,
               lang: str = "hi") -> None:
    """Store a CheckResult. replace=False keeps an existing row (used for cache hits)."""
    extra = (result.get("numbers", {}).get("extra") or {}).get("value")
    on_conflict = ("DO UPDATE SET " + ", ".join(f"{c} = excluded.{c}" for c in _CHECK_COLUMNS[1:])
                   if replace else "DO NOTHING")
    with _db() as conn:
        conn.execute(
            f"INSERT INTO checks ({', '.join(_CHECK_COLUMNS)}) VALUES ({', '.join('?' * len(_CHECK_COLUMNS))}) "
            f"ON CONFLICT (id) {on_conflict}",
            (result["id"], now_ist(), source, image_sha256, result.get("verdict"), extra,
             result.get("seconds"), json.dumps(result.get("engines") or {}),
             json.dumps(result, ensure_ascii=False), lang))
        conn.commit()


def get_check(check_id: str) -> dict | None:
    with _db() as conn:
        row = conn.execute("SELECT result_json FROM checks WHERE id = ?", (check_id,)).fetchone()
    return json.loads(row["result_json"]) if row else None


def get_check_by_image(image_sha256: str) -> dict | None:
    """The first stored answer for this photo key (the cache's backup when its file is gone)."""
    with _db() as conn:
        row = conn.execute("SELECT result_json FROM checks WHERE image_sha256 = ? "
                           "ORDER BY created_at, id LIMIT 1", (image_sha256,)).fetchone()
    return json.loads(row["result_json"]) if row else None


def check_lang(check_id: str) -> str:
    """The language a check was spoken in ("hi" if unknown), to make its MP3 again."""
    with _db() as conn:
        row = conn.execute("SELECT lang FROM checks WHERE id = ?", (check_id,)).fetchone()
    return (row["lang"] if row else None) or "hi"


def list_checks(limit: int = 20) -> list[dict]:
    """Newest first."""
    with _db() as conn:
        rows = conn.execute("SELECT result_json FROM checks ORDER BY created_at DESC, id DESC LIMIT ?",
                            (max(int(limit), 0),)).fetchall()
    return [json.loads(r["result_json"]) for r in rows]


def check_summaries() -> list[dict]:
    """verdict, extra and seconds of every stored check (for /api/stats)."""
    with _db() as conn:
        rows = conn.execute("SELECT verdict, extra, seconds FROM checks").fetchall()
    return [dict(r) for r in rows]


def max_check_number() -> int:
    """Highest N in a stored id chk_NNNN (0 if none), so new ids never repeat."""
    with _db() as conn:
        rows = conn.execute("SELECT id FROM checks WHERE id LIKE ?", ("chk_%",)).fetchall()
    numbers = [int(r["id"][4:]) for r in rows if r["id"][4:].isdigit()]
    return max(numbers, default=0)


# ---------------------------------------------------------------- cases and events
def _next_id(conn, table: str, prefix: str) -> str:
    rows = conn.execute(f"SELECT id FROM {table} WHERE id LIKE ?", (prefix + "%",)).fetchall()
    numbers = [int(r["id"][len(prefix):]) for r in rows if r["id"][len(prefix):].isdigit()]
    return f"{prefix}{max(numbers, default=0) + 1:04d}"


def _new_code(conn) -> str:
    """8 random digits, never starting with 0, not used by another case (D59)."""
    while True:
        code = str(secrets.randbelow(90_000_000) + 10_000_000)
        if not conn.execute("SELECT 1 FROM cases WHERE code = ?", (code,)).fetchone():
            return code


def create_case(borrower_name: str, lender_name: str, check_id: str | None, route: str | None = None,
                borrower_phone: str | None = None, source: str = "app",
                telegram_chat: str | None = None) -> dict:
    """A new case with a random id (nobody can guess it) and its own 8-digit code, made once and never
    changed (D59). borrower_phone must already be masked (XXXXXX 1234): the full number is never stored."""
    with _db() as conn:
        case_id = "case_" + secrets.token_hex(8)
        conn.execute("INSERT INTO cases (id, borrower_name, lender_name, check_id, route, opened_at, code, "
                     "borrower_phone, source, telegram_chat) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
                     (case_id, borrower_name, lender_name, check_id, route, now_ist(), _new_code(conn),
                      borrower_phone, source, telegram_chat))
        conn.commit()
    return get_case(case_id)


def get_case_by_code(code: str) -> dict | None:
    with _db() as conn:
        row = conn.execute("SELECT id FROM cases WHERE code = ?", (code,)).fetchone()
    return get_case(row["id"]) if row else None


def case_for_chat(telegram_chat: str) -> dict | None:
    """The newest case of this Telegram chat (its scrambled key), so the bot finds it after a restart."""
    with _db() as conn:
        row = conn.execute("SELECT id FROM cases WHERE telegram_chat = ? ORDER BY opened_at DESC, id DESC "
                           "LIMIT 1", (telegram_chat,)).fetchone()
    return get_case(row["id"]) if row else None


def set_case_phone(case_id: str, borrower_phone: str) -> bool:
    """Store the borrower's masked phone on a case. False if there is no such case."""
    with _db() as conn:
        found = conn.execute("SELECT 1 FROM cases WHERE id = ?", (case_id,)).fetchone()
        if found:
            conn.execute("UPDATE cases SET borrower_phone = ? WHERE id = ?", (borrower_phone, case_id))
            conn.commit()
    return bool(found)


def chat_lang(telegram_chat: str) -> str | None:
    """The voice language a Telegram chat picked with /bhasha, or None."""
    with _db() as conn:
        row = conn.execute("SELECT lang FROM chats WHERE chat_key = ?", (telegram_chat,)).fetchone()
    return row["lang"] if row else None


def set_chat_lang(telegram_chat: str, lang: str) -> None:
    with _db() as conn:
        conn.execute("INSERT INTO chats (chat_key, lang) VALUES (?, ?) "
                     "ON CONFLICT (chat_key) DO UPDATE SET lang = excluded.lang", (telegram_chat, lang))
        conn.commit()


def add_event(case_id: str, event: dict, photos: list[dict] | None = None) -> dict:
    """Store one event exactly as given: at, channel, contacted, text, rules, hash, prev_hash, threat_type,
    and its photos ({id, sha256, data}, in order) in the same transaction (D60).

    The caller (F2) works out rules and hash; this only stores them, in order.
    """
    photos = photos or []
    with _db() as conn:
        if not conn.execute("SELECT 1 FROM cases WHERE id = ?", (case_id,)).fetchone():
            raise KeyError(case_id)
        event_id = _next_id(conn, "events", "evt_")
        conn.execute("INSERT INTO events (id, case_id, at, channel, contacted, text, rules, hash, prev_hash, "
                     "threat_type) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
                     (event_id, case_id, event["at"], event.get("channel"), event.get("contacted"),
                      event.get("text", ""), json.dumps(list(event.get("rules") or [])),
                      event["hash"], event["prev_hash"], event.get("threat_type")))
        for position, photo in enumerate(photos):
            conn.execute("INSERT INTO photos (id, event_id, case_id, position, sha256, data) VALUES (?, ?, ?, ?, ?, ?)",
                         (photo["id"], event_id, case_id, position, photo["sha256"], photo["data"]))
        conn.commit()
    return {"id": event_id, "at": event["at"], "channel": event.get("channel"),
            "contacted": event.get("contacted"), "text": event.get("text", ""),
            "rules": list(event.get("rules") or []), "hash": event["hash"], "prev_hash": event["prev_hash"],
            "threat_type": event.get("threat_type"),
            "photos": [{"id": p["id"], "sha256": p["sha256"]} for p in photos]}


def _events(conn, case_id: str) -> list[dict]:
    rows = conn.execute("SELECT id, at, channel, contacted, text, rules, hash, prev_hash, threat_type FROM events "
                        "WHERE case_id = ? ORDER BY seq", (case_id,)).fetchall()
    photos: dict[str, list[dict]] = {}
    for p in conn.execute("SELECT id, event_id, sha256 FROM photos WHERE case_id = ? ORDER BY event_id, position",
                          (case_id,)).fetchall():
        photos.setdefault(p["event_id"], []).append({"id": p["id"], "sha256": p["sha256"]})
    return [{**dict(r), "rules": json.loads(r["rules"]), "photos": photos.get(r["id"], [])} for r in rows]


def get_photo(case_id: str, photo_id: str) -> bytes | None:
    """One photo's JPEG bytes, only through its own case (the case id is the secret)."""
    with _db() as conn:
        row = conn.execute("SELECT data FROM photos WHERE id = ? AND case_id = ?", (photo_id, case_id)).fetchone()
    return bytes(row["data"]) if row else None


def close_case(case_id: str, reason: str, note: str | None) -> str | None:
    """Close a case for good (D60): "closed", "already" (it was closed before), or None (no such case)."""
    with _db() as conn:
        row = conn.execute("SELECT closed_at FROM cases WHERE id = ?", (case_id,)).fetchone()
        if not row:
            return None
        if row["closed_at"]:
            return "already"
        conn.execute("UPDATE cases SET closed_at = ?, close_reason = ?, close_note = ? WHERE id = ?",
                     (now_ist(), reason, note, case_id))
        conn.commit()
    return "closed"


def get_case(case_id: str) -> dict | None:
    """The case with its events in the order they were logged (day counter is added by the caller)."""
    with _db() as conn:
        row = conn.execute("SELECT * FROM cases WHERE id = ?", (case_id,)).fetchone()
        if not row:
            return None
        return {**dict(row), "events": _events(conn, case_id)}


def last_event_hash(case_id: str) -> str:
    """Hash of the case's latest event, or GENESIS_HASH for its first one (F2 chains on this)."""
    with _db() as conn:
        row = conn.execute("SELECT hash FROM events WHERE case_id = ? ORDER BY seq DESC LIMIT 1",
                           (case_id,)).fetchone()
    return row["hash"] if row else GENESIS_HASH


def calls_on(case_id: str, date: str) -> int:
    """How many call events this case has on a date (YYYY-MM-DD, from the event's own time). For H6."""
    with _db() as conn:
        row = conn.execute("SELECT COUNT(*) AS n FROM events WHERE case_id = ? AND channel = 'call' "
                           "AND substr(at, 1, 10) = ?", (case_id, date)).fetchone()
    return int(row["n"])
